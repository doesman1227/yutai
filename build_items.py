def parse(block):
    items = []
    for line in block.strip().splitlines():
        code, name, cat, value, cond, fix, arrive, note = line.split("|")
        items.append({
            "code": code.strip(),
            "name": name.strip(),
            "cat": cat.strip() or "その他",
            "value": int(value) if value.strip() else None,
            "cond": cond.strip(),
            "fix": [m for m in fix.split(",") if m.strip()],
            "arrive": [m for m in arrive.split(",") if m.strip()],
            "note": note.strip(),
        })
    return items


def main():
    items = parse(ROWS)
    slugs = dict(l.split("|") for l in SLUGS.strip().splitlines())
    for it in items:
        if it["code"] in PICKS:
            it["memo"] = PICKS[it["code"]]
        if it["code"] in slugs:
            it["url"] = SITE.format(slugs[it["code"]])

    unknown = [c for c in PICKS if c not in {i["code"] for i in items}]
    if unknown:
        raise SystemExit(f"PICKS に一覧外のコードがある: {unknown}")

    bad = [i["code"] for i in items if any(m not in MONTHS for m in i["fix"] + i["arrive"])]
    if bad:
        raise SystemExit(f"月の書き方が不正: {bad}")

    stray = [c for c in slugs if c not in {i["code"] for i in items}]
    if stray:
        raise SystemExit(f"SLUGS に一覧外のコードがある: {stray}")

    nolink = [i["code"] for i in items if "url" not in i]
    if nolink:
        raise SystemExit(f"リンク先が未登録: {nolink}")

    uses, seen, by_code = [], [], {i["code"]: i for i in items}
    for line in USES.strip().splitlines():
        if line.startswith("  "):
            sub, codes = line.strip().split("|")
            codes = [c.strip() for c in codes.split(",") if c.strip()]
            uses[-1]["subs"].append(sub)
            uses[-1]["n"] += len(codes)
            seen += codes
            for c in codes:
                if c in by_code:
                    by_code[c]["use"], by_code[c]["sub"] = uses[-1]["name"], sub
        else:
            name, en = line.split("|")
            uses.append({"name": name, "en": en, "subs": [], "n": 0})

    dup = {c for c in seen if seen.count(c) > 1}
    if dup:
        raise SystemExit(f"USES で二重に置かれたコードがある: {sorted(dup)}")

    ghost = [c for c in seen if c not in by_code]
    if ghost:
        raise SystemExit(f"USES に一覧外のコードがある: {ghost}")

    out_codes = [c.strip() for c in OUT.replace("\n", "").split(",") if c.strip()]
    stray_out = [c for c in out_codes if c not in by_code]
    if stray_out:
        raise SystemExit(f"OUT に一覧外のコードがある: {stray_out}")

    # 新しい銘柄を足したときの入れ忘れを防ぐ。どこかに置くか、出さないと決めるか。
    nowhere = [c for c in by_code if c not in seen and c not in out_codes]
    if nowhere:
        raise SystemExit(f"USES にも OUT にも無いコードがある: {nowhere}")

    wants = []
    for line in WANTS.strip().splitlines():
        code, name, cat, value, fix, arrive, note, use, sub, slug = line.split("|")
        w = {"code": code, "name": name, "cat": cat,
             "value": int(value) if value.strip() else None,
             "fix": [m for m in fix.split(",") if m.strip()],
             "arrive": [m for m in arrive.split(",") if m.strip()],
             "note": note}
        if use.strip():
            w["use"], w["sub"] = use.strip(), sub.strip()
        if slug.strip():
            w["url"] = SITE.format(slug.strip())
        wants.append(w)

    # 持っている銘柄が「欲しい」に残っていると、読む人には何のことか分からない
    held = [w["code"] for w in wants if w["code"] in by_code]
    if held:
        raise SystemExit(f"もう持っている銘柄が WANTS にある: {held}")

    names = {u["name"] for u in uses}
    strayu = [w["code"] for w in wants if w.get("use") and w["use"] not in names]
    if strayu:
        raise SystemExit(f"WANTS の領域がジャンル別に無い: {strayu}")

    halfu = [w["code"] for w in wants if bool(w.get("use")) != bool(w.get("sub"))]
    if halfu:
        raise SystemExit(f"WANTS の領域と細目は両方書くか両方空にする: {halfu}")

    badw = [w["code"] for w in wants if any(m not in MONTHS for m in w["fix"] + w["arrive"])]
    if badw:
        raise SystemExit(f"WANTS の月の書き方が不正: {badw}")

    data = {
        "note": "公開してよい列だけを持つ。株主番号・取得コスト・保有株数・評価損益・利回りは入れない。"
                "更新は build_items.py の ROWS を直してから python3 build_items.py を実行する。",
        "updated": date.today().isoformat(),
        "uses": uses,
        "months": MONTHS,
        "wants": wants,
        "items": items,
    }
    out = Path(__file__).with_name("items.json")
    out.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"{len(items)}件を {out.name} に書き出した")


if __name__ == "__main__":
    main()
